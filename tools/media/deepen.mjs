/** 「自社に当てはめて考える」セクション。ハブ固有の観点があればそれを使う */
export function applySection(c, r) {
  const items = c.points && c.points.length
    ? c.points.slice(0, 4)
    : (c.group === 'area'
      ? [
        `${c.subject}のどの生活圏の学生を対象にするかが決まっているかどうか`,
        '募集要項に勤務地が市区町村まで書かれているかどうか',
        '接点の経路ごとに昨年の実績人数を出せるかどうか',
        '応募から一次面接までの日数が決まっているかどうか',
      ]
      : [
        `${c.subject}で募集する職種ごとに、募集要項が分かれているかどうか`,
        '入社1年目と3年目に任せる範囲が書かれているかどうか',
        '勤務地と通勤手段が具体的に書かれているかどうか',
        '選考の流れと所要日数を学生に先に伝えているかどうか',
      ]);
  return {
    h: '自社に当てはめて考える',
    p: [r.pick(APPLY_LEAD)()],
    list: items,
    after: [r.pick(APPLY_CLOSE)()],
  };
}

