/** ハブ間の内部リンクを作る。同じグループ内＋関連グループから決定的に選ぶ */
export function relatedHubs(hub, hubs, prefBySlug, r) {
  const sameGroup = hubs.filter((h) => h.group === hub.group && h.slug !== hub.slug);
  const issues = hubs.filter((h) => h.group === 'issue');
  const drs = hubs.filter((h) => h.group === 'dr');
  const themes = hubs.filter((h) => h.group === 'theme');

  let near = [];
  if (hub.group === 'area') {
    const block = prefBySlug.get(hub.pref).block;
    near = sameGroup.filter((h) => prefBySlug.get(h.pref).block === block);
    if (near.length < 3) near = sameGroup;
  } else {
    near = sameGroup;
  }

  const pool2 = hub.group === 'issue' ? [...drs, ...themes]
    : hub.group === 'dr' ? [...issues, ...themes]
      : hub.group === 'theme' ? [...issues, ...drs]
        : [...issues, ...drs];

  return [...r.some(near, 3), ...r.some(pool2, 3)];
}

