const QA_ALL = Object.fromEntries(Object.keys(QA).map((k) => [k, [...QA[k], ...(QA_EXTRA[k] ?? [])]]));

/** よくある質問セクションを1つ返す */
export function qaSection(c, r) {
  const bank = QA_ALL[c.group] ?? QA_ALL.issue;
  const picked = r.some(bank, 3).map((f) => f(c));
  return {
    h: 'よくある質問',
    qa: picked.map(([q, a]) => ({ q, a })),
  };
}

