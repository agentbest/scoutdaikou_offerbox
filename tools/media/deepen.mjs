const MISREAD_ALL = Object.fromEntries(
  Object.keys(MISREAD).map((k) => [k, [...MISREAD[k], ...(MISREAD_EXTRA[k] ?? [])]]));

/** 「よくある誤解」セクション。グループごとのバンクから3つ選ぶ */
export function misreadSection(c, r) {
  const bank = MISREAD_ALL[c.group] ?? MISREAD_ALL.issue;
  return { h: 'よくある誤解', p: r.some(bank, 3).map((f) => f(c)) };
}

/* ---------- ハブ固有の前提（同じ切り口の記事が県ごと・業種ごとに入れ替わる部分） ---------- */
//
// 切り口（angles-*.mjs）の章立ては全ハブで共通なので、これだけだと
// 「北海道の◯◯」と「青森県の◯◯」が県名しか違わない記事になる。
// ここでハブのデータ（主要産業・都市・大学／募集職種／観点）から
// そのハブでしか成立しない段落を作り、記事ごとの中身を入れ替えている。

export function hubFactsSection(c, r) {
  if (c.group === 'area') {
    const inP = c.inPref || '県内';
    const outP = c.outPref || '県外';
    return {
      h: `${c.subject}の採用を考えるときの基礎データ`,
      p: [
        `${c.subject}の主な産業は${c.industries.join('、')}である。企業の集積は${c.capital}と${c.cities[1]}に偏りやすく、${c.cities.slice(2).join('・')}に拠点を置く会社ほど、通勤と住まいの条件を先に示さないと比較の土俵に乗りにくい。`,
        `${inP}の主な高等教育機関としては${c.universities.join('、')}が挙げられる。学校経由の接点はここが起点になるが、それだけでは${outP}に進学した${c.short}出身の学生には届かない。両者は別の対象として設計したい。`,
        `${c.blockLabel}という括りで見ると、${c.short}の企業が比較される相手は三つに分かれる。${c.blockLabel}の同業、${c.capital}に拠点を持つ企業、そして学生が進学先で接している都市部の企業である。どれと比べられているかで、出すべき条件が変わる。`,
      ],
    };
  }
  if (c.group === 'industry') {
    const roles = c.roles || [];
    return {
      h: `${c.subject}で募集する職種を分けて考える`,
      p: [
        `${c.subject}が新卒で募集する職種は、${roles.join('、')}などに分かれる。同じ会社の募集でも、職種が違えば競合も、学生が比較する軸も変わる。`,
        `たとえば${roles[0]}と${roles[roles.length - 1]}では、学生が見ている条件も、入社後に求められる資質も異なる。ひとつの募集要項にまとめると、どちらの層にも届かない文章になりやすい。`,
        c.note,
      ],
    };
  }
  // 課題・スカウト採用・テーマのハブは、note と観点からハブ固有の段落を作る
  const pts = c.points || [];
  return {
    h: `${c.subject}を自社の言葉にする`,
    p: [
      c.note,
      `自社の話に落とすときは、${pts[0] ? pts[0].replace(/かどうか$/, '') : 'いま決まっていること'}、${pts[1] ? pts[1].replace(/かどうか$/, '') : '担当と期限'}、この二つから確認するのが早い。ここが曖昧なままだと、どの手法を選んでも判断の基準が作れない。`,
      `あわせて、${pts[2] ? pts[2].replace(/かどうか$/, '') : '記録が残っているか'}も見ておきたい。ここは後回しにされやすいが、翌年に同じ議論を繰り返すかどうかの分かれ目になる。`,
    ].filter(Boolean),
  };
}
