/** 「北海道の中小企業」「製造業の中小企業」のように主語を作る */
export function who(ctx, kind = 'company') {
  const s = ctx.subject;
  if (ctx.group === 'area') {
    return { company: `${s}の企業`, smb: `${s}の中小企業`, here: s, at: `${s}で`, of: `${s}の` }[kind];
  }
  if (ctx.group === 'industry') {
    return { company: `${s}の企業`, smb: `${s}の中小企業`, here: s, at: `${s}で`, of: `${s}の` }[kind];
  }
  return { company: '企業', smb: '中小企業', here: s, at: '', of: '' }[kind];
}

