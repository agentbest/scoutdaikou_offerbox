export const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** 主要都市を「札幌・旭川・函館」のように並べる */
export const joinCities = (cities, n = 3) => cities.slice(0, n).join('・');

/** 産業を「食品加工や農業」のように自然文に入れる */
export const joinIndustries = (list, n = 2) => {
  const a = list.slice(0, n);
  return a.length >= 2 ? `${a[0]}や${a[1]}` : a[0];
};

