/* ---------- 都道府県の言い換え ---------- */
//
// 切り口（angles-area*.mjs）の文面は「県内」「県外」で書いてある。
// 北海道・東京都・大阪府・京都府では日本語として不自然になるので、
// 生成時にその県の言い方へ置き換える。
// ⚠ 置き換え対象は「県内」「県外」「県名」だけ。ここを増やすと、
//   都道府県名を含む固有名詞（県庁所在地 など）まで壊す恐れがある。
const PREF_WORDS = {
  hokkaido: { 県内: '道内', 県外: '道外' },
  tokyo: { 県内: '都内', 県外: '都外' },
  osaka: { 県内: '府内', 県外: '府外' },
  kyoto: { 県内: '府内', 県外: '府外' },
};

export function localizePref(text, prefSlug) {
  let out = String(text).replace(/県名/g, '都道府県名');
  const w = PREF_WORDS[prefSlug];
  if (!w) return out;
  for (const [from, to] of Object.entries(w)) out = out.split(from).join(to);
  return out;
}
